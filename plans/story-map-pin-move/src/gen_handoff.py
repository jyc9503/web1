def rows(spec, state):
    out = []
    for line in spec.splitlines():
        m = re.match(r"\| ([A-Z]{1,3}-\d+) \| (.*) \| \{" + state + r"\} \|$", line)
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def ids(spec, state):
    return ", ".join(i for i, _ in rows(spec, state))


def short(cells, n=70):
    t = re.sub(r"\*\*|`", "", cells.split(" | ")[-1])
    return t[:n] + "…" if len(t) > n else t


def body(s):
    return re.sub(r"^---\n.*?\n---\n", "", s, flags=re.S).strip()


def demote(s):
    return re.sub(r"^(#{2,3}) ", lambda m: "#" + m.group(1) + " ", s, flags=re.M)


def fm(s, k):
    return re.search(r"^" + k + r": (.*)$", s, re.M).group(1)


